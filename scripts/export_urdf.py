#!/usr/bin/env python3
"""Export the URDF trees that exist in this repository and refresh the 3D viewer.

Sources (nothing is measured here; values are copied from the configs as they are):
- vendor static TFs: chassis_vendor/turn_on_wheeltec_robot/config/robot_model.yaml, the same
  base_footprint children that robot_mode_description.launch.py publishes for the car mode;
- gimbal URDF: gimbal_bridge.urdf.build_urdf() on gimbal_bridge/config/gimbal_mount.yaml;
- combined: vendor tree with its fixed base_footprint -> camera_link replaced by the gimbal
  chain, as gimbal.launch.py requires (the vendor camera TF must be off).

The vendor mesh URDF (wheeltec_robot_urdf/urdf/<car>_robot.urdf) is not in this repository.
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.dom import minidom

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'ros2_ws/src'
sys.path.insert(0, str(SRC / 'gimbal_bridge'))
from gimbal_bridge.urdf import build_urdf, load_mount  # noqa: E402

MODEL_YAML = SRC / 'chassis_vendor/turn_on_wheeltec_robot/config/robot_model.yaml'
MOUNT_YAML = SRC / 'gimbal_bridge/config/gimbal_mount.yaml'
OUT_DIR = ROOT / 'docs/diagrams/urdf'
VIEWER = ROOT / 'docs/diagrams/URDF模型3D.html'
# Same mapping as robot_mode_description.launch.py (parent base_footprint).
VENDOR_TF = {'base_to_link': 'base_link', 'base_to_gyro': 'gyro_link',
             'base_to_laser': 'laser', 'base_to_camera': 'camera_link', 'base_to_radar': 'radar'}


def _fmt(values):
    return ' '.join(f'{float(v):.6f}' for v in values)


def vendor_urdf(car_mode):
    models = yaml.safe_load(MODEL_YAML.read_text(encoding='utf-8'))['robot_model']
    if car_mode not in models:
        raise SystemExit(f'unknown car mode {car_mode!r}; known: {", ".join(models)}')
    robot = ET.Element('robot', name=f'{car_mode}_static_tf')
    ET.SubElement(robot, 'link', name='base_footprint')
    for key, child in VENDOR_TF.items():
        if key not in models[car_mode]:
            continue
        x, y, z, yaw, pitch, roll = models[car_mode][key]  # static_transform_publisher order
        ET.SubElement(robot, 'link', name=child)
        joint = ET.SubElement(robot, 'joint', name=key, type='fixed')
        ET.SubElement(joint, 'parent', link='base_footprint')
        ET.SubElement(joint, 'child', link=child)
        ET.SubElement(joint, 'origin', xyz=_fmt((x, y, z)), rpy=_fmt((roll, pitch, yaw)))
    return robot


def combined_urdf(vendor, gimbal, car_mode):
    robot = ET.Element('robot', name=f'{car_mode}_gimbal')
    names = set()
    for source in (vendor, gimbal):
        for link in source.findall('link'):
            if link.get('name') not in names:
                names.add(link.get('name'))
                robot.append(link)
    camera = gimbal.find("joint[@name='camera_mount_joint']/child").get('link')
    parent = gimbal.find("joint[@name='pan_joint']/parent").get('link')
    if parent != 'base_footprint':
        raise SystemExit(f'gimbal parent_frame {parent!r} is not the vendor root base_footprint')
    for joint in vendor.findall('joint'):
        if joint.find('child').get('link') != camera:
            robot.append(joint)
    for joint in gimbal.findall('joint'):
        robot.append(joint)
    return robot


def pretty(robot, comment):
    text = minidom.parseString(ET.tostring(robot)).toprettyxml(indent='  ')
    head, body = text.split('\n', 1)
    return f'{head}\n<!-- {comment} -->\n{body}'


def inject(html, key, urdf):
    pattern = re.compile(rf'(<script type="text/plain" id="urdf-{key}">)(.*?)(</script>)', re.S)
    if not pattern.search(html):
        raise SystemExit(f'viewer is missing the urdf-{key} block')
    return pattern.sub(lambda m: m.group(1) + '\n' + urdf + m.group(3), html, count=1)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--car-mode', default='mini_akm')
    parser.add_argument('--check', action='store_true', help='exit 1 if any output is stale')
    args = parser.parse_args()

    mount = load_mount(MOUNT_YAML)
    status = 'confirmed' if mount['confirmed'] else 'PLACEHOLDER (confirmed: false, not measured)'
    vendor = vendor_urdf(args.car_mode)
    gimbal = ET.fromstring(build_urdf(mount))
    rel = lambda p: p.relative_to(ROOT).as_posix()  # noqa: E731
    outputs = {
        OUT_DIR / f'{args.car_mode}_static_tf.urdf': pretty(
            vendor, f'Generated by scripts/export_urdf.py from {rel(MODEL_YAML)} ({args.car_mode}); frames only, no meshes.'),
        OUT_DIR / 'roscar_gimbal.urdf': pretty(
            gimbal, f'Generated by scripts/export_urdf.py via gimbal_bridge.urdf.build_urdf({rel(MOUNT_YAML)}); {status}.'),
        OUT_DIR / f'{args.car_mode}_gimbal_combined.urdf': pretty(
            combined_urdf(vendor, gimbal, args.car_mode),
            f'Generated by scripts/export_urdf.py: vendor {args.car_mode} static TFs with base_to_camera replaced '
            f'by the gimbal chain; gimbal {status}.'),
    }
    html = VIEWER.read_text(encoding='utf-8')
    names = list(outputs)
    html = inject(html, 'vendor', outputs[names[0]])
    html = inject(html, 'combined', outputs[names[2]])
    outputs[VIEWER] = html

    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding='utf-8') != text]
    if args.check:
        for path in stale:
            print(f'stale: {rel(path)}')
        return 1 if stale else 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_text(outputs[path], encoding='utf-8')
        print(f'wrote {rel(path)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
